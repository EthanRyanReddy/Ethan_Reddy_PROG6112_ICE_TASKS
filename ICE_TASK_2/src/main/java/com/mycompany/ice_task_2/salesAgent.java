public class salesAgent extends Employees implements IvehicleDealer {

 private int vehiclesSold; 
 
 private double comissionRate; 
 
 public salesAgent(String name, String employeeID, double baseSalary, int vehiclesSold, double commissionRate){
     
     super(name, employeeID, baseSalary); 
     
     this.vehiclesSold = vehiclesSold;
     this.comissionRate = comissionRate; 
 }
 
 @Override
 public double calcComission(){
     return vehiclesSold * comissionRate; 
 }
 @Override
 public void generateQoute(){
     System.out.println("Vehnicel qoute generated by" + name);
 }
 
 public void printReport(){
     
     double comission = calcComission();; 
     double monthlyEarnings = baseSalary + comission; 
     
     System.out.println("******************************");
     System.out.println("      Sales Agent Report   ");
     System.out.println("******************************");
     
     System.out.println("Agent Name:" + name);
     System.out.println("Employee ID" + employeeID);
     System.out.printf("BaseSalary: R%.2f%n", baseSalary);
     System.out.println("Vehicles Sold" + vehiclesSold);
     System.out.printf("Commission Earned: R%.2f%n " , comission);
     System.out.printf("Total Earnings: R%.2f%n " , monthlyEarnings);
     
     if(comission > 10000){
         
         System.out.println("Top Seller!"); 
     }
     
     
     
 }
 
}
